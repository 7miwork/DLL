_current_language: str = "en"
_display_bilingual: bool = False


def set_language(code: str) -> None:
    global _current_language
    if code in TRANSLATIONS:
        _current_language = code
    else:
        _current_language = "en"


def get_language() -> str:
    return _current_language


def set_bilingual(enabled: bool = True) -> None:
    """Show English and Traditional Chinese together in the application UI."""
    global _display_bilingual
    _display_bilingual = bool(enabled)


def is_bilingual() -> bool:
    return _display_bilingual


def _format(template: str, kwargs: dict) -> str:
    if kwargs:
        try:
            return template.format(**kwargs)
        except (KeyError, ValueError):
            return template
    return template


def tr(key: str, **kwargs) -> str:
    lang = _current_language
    templates = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    template = templates.get(key, TRANSLATIONS["en"].get(key, key))
    if not _display_bilingual:
        return _format(template, kwargs)

    english = _format(TRANSLATIONS["en"].get(key, key), kwargs)
    chinese = _format(TRANSLATIONS["zh_Hant"].get(key, english), kwargs)
    if english == chinese:
        return english
    return f"{english} / {chinese}"
